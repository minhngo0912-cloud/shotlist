#!/usr/bin/env python3
"""Make the lakes of Central Park (src/maplakes.js) from OpenStreetMap water outlines.

Source: central-park-water.geojson, an OpenStreetMap extract (© OpenStreetMap contributors, ODbL 1.0):
  curl -sLO https://raw.githubusercontent.com/parkerbossier/loop/HEAD/geo/central-park-water.geojson

Usage: python3 tools/make_lakes.py central-park-water.geojson
Writes MAPD_LAKES: [name, SVG path in map units x10 (draw inside scale(0.1)), label lat, label lon, area in m²]
"""
import json, math, os, sys
from shapely.geometry import shape, Point

SRC = sys.argv[1] if len(sys.argv) > 1 else sys.exit(__doc__)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = {"Jacqueline Kennedy Onassis Reservoir": "The Reservoir"}

def xy(lat, lon): return ((lon + 74.30) * 0.758 * 2000, (40.95 - lat) * 2000)
def dp(pts, tol):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]; dx, dy = b[0]-a[0], b[1]-a[1]; L = math.hypot(dx, dy) or 1e-9
    i, dmax = 0, -1
    for k in range(1, len(pts)-1):
        p = pts[k]; d = abs(dy*(p[0]-a[0]) - dx*(p[1]-a[1])) / L
        if d > dmax: i, dmax = k, d
    if dmax <= tol: return [a, b]
    return dp(pts[:i+1], tol)[:-1] + dp(pts[i:], tol)
def ring(coords):            # lon,lat ring -> closed path in map units x10, simplified to about 1.5 m
    p = [xy(lat, lon) for lon, lat in coords]; m = len(p)//2     # a closed ring starts and ends on the same point: simplify it in two halves
    pts = dp(p[:m+1], 0.025)[:-1] + dp(p[m:], 0.025)
    q = [(round(x*10), round(y*10)) for x, y in pts]; out = [q[0]]
    for p in q[1:]:
        if p != out[-1]: out.append(p)
    return "M" + " ".join("%d %d" % p for p in out) + "Z"
def label_point(g):          # the point inside the water farthest from its shore, so the name sits on the water
    x0, y0, x1, y1 = g.bounds; best, bd = None, -1
    for i in range(41):
        for j in range(41):
            p = Point(x0 + (x1-x0)*i/40, y0 + (y1-y0)*j/40)
            if g.contains(p):
                d = g.exterior.distance(p)
                if d > bd: best, bd = p, d
    return best or g.representative_point()

lakes = []
for f in json.load(open(SRC))["features"]:
    g = shape(f["geometry"]); name = f["properties"]["name"]
    polys = [g] if g.geom_type == "Polygon" else list(g.geoms)
    d = "".join(ring(p.exterior.coords) + "".join(ring(h.coords) for h in p.interiors) for p in polys)
    lp = label_point(max(polys, key=lambda p: p.area))
    lakes.append([NAMES.get(name, name), d, round(lp.y, 5), round(lp.x, 5), round(f["properties"].get("area_m2") or 0)])
lakes.sort(key=lambda r: -r[4])
with open(os.path.join(ROOT, "src", "maplakes.js"), "w") as o:
    o.write("/* Generated by tools/make_lakes.py from OpenStreetMap water outlines (© OpenStreetMap contributors, ODbL). Do not edit by hand. */\n")
    o.write("const MAPD_LAKES = " + json.dumps(lakes, separators=(",", ":")) + ";\n")
print(len(lakes), "lakes,", sum(len(r[1]) for r in lakes), "bytes of path")
